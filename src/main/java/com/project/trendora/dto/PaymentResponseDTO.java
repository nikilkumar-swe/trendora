package com.project.trendora.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.Data;

@Data
@Schema(
        name = "PaymentResponseDTO",
        description = "Response DTO containing Razorpay payment order details"
)
public class PaymentResponseDTO {
    @Schema(
            description = "Unique order ID generated by Razorpay",
            example = "order_Rx123456789"
    )
    private String razorpayOrderId;

    @Schema(
            description = "Unique ID of the order in Trendora",
            example = "1"
    )
    private Long orderId;
    @Schema(
            description = "Payment amount for the order",
            example = "4998.00"
    )
    private Double amount;
    @Schema(
            description = "Currency used for the payment",
            example = "INR"
    )
    private String currency;

}
