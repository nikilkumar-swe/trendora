package com.project.trendora.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import lombok.Data;

@Data
@Schema(
        name = "PaymentVerificationRequest",
        description = "Request DTO for verifying Razorpay payment authenticity using payment details and signature"
)
public class PaymentVerificationRequest {

    @NotBlank
    @Schema(
            description = "Unique Razorpay order ID generated during payment creation",
            example = "order_Rx123456789",
            requiredMode = Schema.RequiredMode.REQUIRED
    )
    private String razorpayOrderId;

    @NotBlank
    @Schema(
            description = "Unique payment ID generated by Razorpay after payment",
            example = "pay_Rx987654321",
            requiredMode = Schema.RequiredMode.REQUIRED
    )
    private String razorpayPaymentId;

    @NotBlank
    @Schema(
            description = "Cryptographic signature generated by Razorpay for payment verification",
            example = "a1b2c3d4e5f678901234567890abcdef1234567890abcdef1234567890abcdef",
            requiredMode = Schema.RequiredMode.REQUIRED
    )
    private String razorpaySignature;
}